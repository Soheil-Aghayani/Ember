/** The words for [language] ("en", "fa", or "system" to follow the phone). */
fun stringsFor(language: String): Strings {
    val code = if (language == "system") Locale.getDefault().language else language
    return if (code == "fa") PersianStrings else EnglishStrings
}

val LocalStrings = staticCompositionLocalOf { EnglishStrings }
