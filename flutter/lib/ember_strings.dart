  String get(String key, [Map<String, Object?> values = const {}]) {
    final text = (persian ? _fa : _en)[key] ?? _en[key] ?? key;
    return values.entries.fold(
      text,
      (result, entry) => result.replaceAll('{${entry.key}}', '${entry.value}'),
    );
  }

